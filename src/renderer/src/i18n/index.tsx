export const translations: Record<Lang, TranslationTable> = { en: EN, zh: ZH }

// ── Context ────────────────────────────────────────────────────────────────

interface I18nContextValue {
  t: (key: TranslationKey) => string
  lang: Lang
  setLang: (l: Lang) => void
}

const I18nContext = createContext<I18nContextValue>({
  t: (key) => key,
  lang: 'zh',
  setLang: () => undefined,
})

// ── Provider ───────────────────────────────────────────────────────────────

export function I18nProvider({ children }: { children: ReactNode }): JSX.Element {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('rgbbox:lang') as Lang | null
    return saved === 'en' || saved === 'zh' ? saved : 'zh'
  })

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    localStorage.setItem('rgbbox:lang', l)
    // R80.12: 通知主进程重建托盘菜单等原生 UI 的语言
    window.rgbbox?.setUiLocale?.(l)
  }, [])

  // R80.12: 启动时把持久化语言同步给主进程（托盘菜单跟随界面语言）
  useEffect(() => {
    window.rgbbox?.setUiLocale?.(lang)
  }, []) // eslint-disable-line react-hooks/exhaustive-deps

  const t = useCallback((key: TranslationKey): string => {
    return translations[lang][key] ?? key
  }, [lang])

  // Value is stable per lang change (memoised inline via useCallback deps)
  return (
    <I18nContext.Provider value={{ t, lang, setLang }}>
      {children}
    </I18nContext.Provider>
  )
}

// ── Hook ───────────────────────────────────────────────────────────────────

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
